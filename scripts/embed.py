#!/usr/bin/env python3
"""Embed web/index.html into a C header as a base64 string literal.

CPA decodes the plugin's management response Body as JSON []byte (base64),
so the page is stored pre-encoded.
"""
import base64
import sys

src, dst = sys.argv[1], sys.argv[2]
with open(src, "rb") as f:
    encoded = base64.b64encode(f.read()).decode("ascii")

lines = [encoded[i : i + 100] for i in range(0, len(encoded), 100)] or [""]
with open(dst, "w", encoding="ascii", newline="\n") as f:
    f.write("/* generated by scripts/embed.py from %s - do not edit */\n" % src)
    f.write("#pragma once\n")
    f.write("static const char PAGE_B64[] =\n")
    for line in lines:
        f.write('\t"%s"\n' % line)
    f.write(";\n")
